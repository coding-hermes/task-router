#!/usr/bin/env python3
"""TR-200: mechanically drop the dead columns from model_catalog.jsonl.

model_catalog.jsonl is NOT generated by router_seed.py — its writer is
router_modelsdev.py run_sync (plus router_clinepass.py), and neither writer
rewrites EXISTING rows (run_sync only appends new (provider, model) pairs, the
TR-035 refresh lane only touches models.jsonl). So removing the columns from
the writers cannot clean the committed table — this repair does, once, the
same way fix_overlay_wipes_tr198.py repairs its one-time wipe: rewrite each
row as a dict WITHOUT the dead keys and verify the census is clean.

Dead keys (verified 0/1187 non-null on 2026-10-12, the TR-200 census):
    vision, modality, knowledge_cutoff

Idempotent: a second run rewrites nothing. NEVER hand-edit the JSONL — this
script is the mechanical repair; the writers above keep the schema gone.
"""
from __future__ import annotations
import json
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO = os.path.dirname(_HERE)
T = os.environ.get("ROUTING_DATA_DIR", os.path.join(_REPO, "data", "tables"))

DEAD_KEYS = ("vision", "modality", "knowledge_cutoff")


def main() -> None:
    path = os.path.join(T, "model_catalog.jsonl")
    rows = []
    with open(path) as f:
        for line in f:
            if line.strip():
                rows.append(json.loads(line))
    n_rows = len(rows)
    cleaned, changed = [], 0
    nonnull_dropped = {}
    for r in rows:
        for k in DEAD_KEYS:
            if r.get(k) is not None and r.get(k) != "":
                nonnull_dropped[k] = nonnull_dropped.get(k, 0) + 1
        new = {k: v for k, v in r.items() if k not in DEAD_KEYS}
        if new != r:
            changed += 1
        cleaned.append(new)
    if nonnull_dropped:
        # The removal is only safe because the columns are 100% null — refuse
        # to silently destroy a value that appeared since the census.
        sys.exit(f"REFUSING: non-null values found in dead columns: {nonnull_dropped}")
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        for r in cleaned:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    os.replace(tmp, path)
    keys = sorted({k for r in cleaned for k in r})
    print(f"model_catalog.jsonl: {n_rows} rows scanned, {changed} rows rewritten, "
          f"dead keys dropped; remaining keys: {keys}")
    assert not (set(DEAD_KEYS) & set(keys)), "dead keys still present"
    print("census clean: no vision/modality/knowledge_cutoff keys remain")


if __name__ == "__main__":
    main()
